package ratify

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"strings"
	"time"

	"intentgate/internal/lock"
)

// BuildInput is everything Build needs to make a lock. RootIntent is the masked text to bind to;
// Build hashes it as given and takes root_intent.redactions from it, so the count always matches
// the scan that produced the text.
type BuildInput struct {
	ID               string // ULID, generated by the caller
	BaseRef          string
	Source           string // claude-code-session | issue | plan-file
	RootIntent       Masked
	Criteria         []lock.Criterion
	Ratifier         string
	RatifiedAt       time.Time // converted to UTC and truncated to seconds
	Method           string    // hook | cli-confirm | issue
	ReviewDurationMS int
	DraftedBy        string // optional: "" leaves drafted_by out
}

// Build makes revision 1 of a lock: empty amendments, root_intent.sha256 the SHA-256 of the
// RootIntent bytes, and the hash set. It returns an error, and the zero Lock, if lock.Validate
// reports any problem.
func Build(in BuildInput) (lock.Lock, error) {
	if in.RatifiedAt.IsZero() {
		return lock.Lock{}, errors.New("ratify: ratified_at is required")
	}
	sum := sha256.Sum256([]byte(in.RootIntent.text))
	redactions, duration := in.RootIntent.redactions, in.ReviewDurationMS
	l := lock.Lock{
		Schema:   lock.SchemaID,
		ID:       in.ID,
		Revision: 1,
		BaseRef:  in.BaseRef,
		RootIntent: lock.RootIntent{
			SHA256:     hex.EncodeToString(sum[:]),
			Source:     in.Source,
			Redactions: &redactions,
		},
		Criteria: in.Criteria,
		Ratification: lock.Ratification{
			Ratifier:         in.Ratifier,
			RatifiedAt:       in.RatifiedAt.UTC().Truncate(time.Second).Format("2006-01-02T15:04:05Z"),
			Method:           in.Method,
			ReviewDurationMS: &duration,
		},
		Amendments: []lock.Amendment{},
	}
	if in.DraftedBy != "" {
		d := in.DraftedBy
		l.Ratification.DraftedBy = &d
	}
	if ps := lock.Validate(l); len(ps) > 0 {
		msgs := make([]string, len(ps))
		for i, p := range ps {
			msgs[i] = p.String()
		}
		return lock.Lock{}, fmt.Errorf("ratify: the lock is invalid: %s", strings.Join(msgs, "; "))
	}
	h, err := lock.Hash(l)
	if err != nil {
		return lock.Lock{}, fmt.Errorf("ratify: %w", err)
	}
	l.Hash = h
	return l, nil
}

// MaskAndBuild is the way to get a Lock from a raw root intent: it scans rawRootIntent first with
// d (nil means gitleaks'), then builds the lock from the masked text and the scan's count, ignoring
// in.RootIntent. It returns the lock and the Masked text, which is what
// Store.Write must be given. A scan error aborts: nothing is built or returned, so no Masked value
// exists for the Store to take.
func MaskAndBuild(d Detector, rawRootIntent string, in BuildInput) (lock.Lock, Masked, error) {
	if d == nil {
		d = gitleaksDetector
	}
	masked, _, err := MaskWith(d, rawRootIntent)
	if err != nil {
		return lock.Lock{}, Masked{}, fmt.Errorf("ratify: secret scan failed, nothing written: %w", err)
	}
	in.RootIntent = masked
	l, err := Build(in)
	if err != nil {
		return lock.Lock{}, Masked{}, err
	}
	return l, masked, nil
}
