package ratify

import (
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"strings"
	"time"

	"intentgate/internal/lock"
)

// BuildInput is everything Build needs to make a lock. RootIntent is the text to bind to: Build
// hashes it as given, so a caller must pass the masked text (MaskAndBuild does).
type BuildInput struct {
	ID               string // ULID, generated by the caller
	BaseRef          string
	Source           string // claude-code-session | issue | plan-file
	RootIntent       string
	Redactions       int // secrets masked in RootIntent
	Criteria         []lock.Criterion
	Ratifier         string
	RatifiedAt       time.Time // converted to UTC and truncated to seconds
	Method           string    // hook | cli-confirm | issue
	ReviewDurationMS int
	DraftedBy        string // optional: "" leaves drafted_by out
}

// Build makes revision 1 of a lock: empty amendments, root_intent.sha256 the SHA-256 of the
// RootIntent bytes, and the hash set. It returns an error, and the zero Lock, if lock.Validate
// reports any problem.
func Build(in BuildInput) (lock.Lock, error) {
	if in.RatifiedAt.IsZero() {
		return lock.Lock{}, errors.New("ratify: ratified_at is required")
	}
	sum := sha256.Sum256([]byte(in.RootIntent))
	redactions, duration := in.Redactions, in.ReviewDurationMS
	l := lock.Lock{
		Schema:   lock.SchemaID,
		ID:       in.ID,
		Revision: 1,
		BaseRef:  in.BaseRef,
		RootIntent: lock.RootIntent{
			SHA256:     hex.EncodeToString(sum[:]),
			Source:     in.Source,
			Redactions: &redactions,
		},
		Criteria: in.Criteria,
		Ratification: lock.Ratification{
			Ratifier:         in.Ratifier,
			RatifiedAt:       in.RatifiedAt.UTC().Truncate(time.Second).Format("2006-01-02T15:04:05Z"),
			Method:           in.Method,
			ReviewDurationMS: &duration,
		},
		Amendments: []lock.Amendment{},
	}
	if in.DraftedBy != "" {
		d := in.DraftedBy
		l.Ratification.DraftedBy = &d
	}
	if ps := lock.Validate(l); len(ps) > 0 {
		msgs := make([]string, len(ps))
		for i, p := range ps {
			msgs[i] = p.String()
		}
		return lock.Lock{}, fmt.Errorf("ratify: the lock is invalid: %s", strings.Join(msgs, "; "))
	}
	h, err := lock.Hash(l)
	if err != nil {
		return lock.Lock{}, fmt.Errorf("ratify: %w", err)
	}
	l.Hash = h
	return l, nil
}

// MaskAndBuild is the way to get a Lock from a raw root intent: it scans in.RootIntent first (nil
// scan means Mask), then builds the lock from the masked text and the scanner's count, ignoring
// in.Redactions. It returns the lock and the masked text, which is what Store.Write must be given.
// A scanner error aborts: nothing is built or returned, so an unscanned root intent can't reach a
// Store.
func MaskAndBuild(scan Scanner, in BuildInput) (lock.Lock, string, error) {
	if scan == nil {
		scan = Mask
	}
	masked, n, err := scan(in.RootIntent)
	if err != nil {
		return lock.Lock{}, "", fmt.Errorf("ratify: secret scan failed, nothing written: %w", err)
	}
	in.RootIntent, in.Redactions = masked, n
	l, err := Build(in)
	if err != nil {
		return lock.Lock{}, "", err
	}
	return l, masked, nil
}
